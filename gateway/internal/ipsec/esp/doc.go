// Package esp 实现 IPSec 的 ESP 数据面（RFC 4303，**隧道模式**），是 ipsec.Protector 的唯一实现。
//
// # 本包在整条链路里的位置
//
//	Datapath(TUN/netstack) ──明文 IP 包──> Protect  ──ESP 报文──> Transport(UDP 4500) ──> 对端
//	Datapath(TUN/netstack) <──明文 IP 包── Unprotect <──ESP 报文── Transport(UDP 4500) <── 对端
//
// 密钥与 SPI 全部由 ike 状态机协商后经 ipsec.ChildSAParams 装载进来；本包**不参与任何协商**，
// 也不 import ike 的状态机——只用 ike 的算法注册表（LookupEncr/LookupInteg）。
// 依赖方向因此是单向的：ipsec ← ike ← esp，本包可以脱离 IKE 单独跑 go test。
//
// # 只做 UDP-4500 封装（RFC 3948），不做裸 ESP（IP 协议号 50）
//
// 这是全局性的取舍，不是偷懒：裸 ESP 要 raw socket + root，本机与 CI 都验证不了，
// 于是「ESP 真的在加解密」就只能靠人在有 root 的机器上肉眼跑一次，退化成又一句
// 不可验证的声明。走 UDP 封装后，本包产出的就是一个普通 UDP 载荷，
// `go test` 里两条内存管道对拨即可端到端自证。
//
// 副作用写在诚实边界里：与 strongSwan 对接需要对端 `forceencap=yes`。
// 另一个正收益是 IKE 与 ESP 共用同一条 socket——NAT 映射按五元组建立，
// ESP 若另开端口，NAT 后的对端根本收不到。
//
// # 线格式（RFC 4303 §2）
//
//	 0                   1                   2                   3
//	+---------------+---------------+---------------+---------------+
//	|                    SPI（4 字节，规定非零）                     |  ┐ AAD / ICV
//	+---------------+---------------+---------------+---------------+  │ 覆盖范围
//	|                  Sequence Number（4 字节）                     |  ┘ 起点
//	+---------------+---------------+---------------+---------------+
//	|  IV（GCM 8 字节显式 nonce / CBC 16 字节随机 IV，**明文上线**）  |
//	+---------------+---------------+---------------+---------------+
//	|                                                               |
//	~   密文 = Enc( 内层整个 IP 包 ‖ Padding ‖ PadLen ‖ NextHeader ) ~
//	|                                                               |
//	+---------------+---------------+---------------+---------------+
//	|        ICV（GCM tag 16 字节 / HMAC 截断 16 字节）              |
//	+---------------+---------------+---------------+---------------+
//
// 隧道模式意味着被加密的是**内层整个 IP 包**（含它自己的 IP 头），NextHeader 因此是
// 4（IPv4）或 41（IPv6），而不是 TCP/UDP 的协议号。外层 IP/UDP 头由内核在发包时补，
// 本包不碰。
//
// # 两个套件在布局上的全部差异（写错的症状都是同一句「解密失败」）
//
//	                   AES/SM4-CBC + HMAC              AES/SM4-GCM-16（combined）
//	INTEG transform    12（或私有 1024）                **必须 0=NONE**
//	加密密钥长度        32（纯密钥）                     36（32 密钥 + **末尾 4 字节 salt**）
//	完整性密钥          32                               **0（不派生）**
//	IV 字段            16 字节，**随机不可预测**          8 字节，**= 该包的序号**
//	真实密码学 nonce    IV 本身                          salt(4) ‖ IV(8)
//	补齐               16 字节对齐                       4 字节对齐（见 packet.go）
//	ICV                HMAC-SHA256/SM3 截断到 16 字节    GCM tag 16 字节
//	AAD / ICV 覆盖      SPI‖Seq‖IV‖密文（除 ICV 外全部） **AAD 只有 SPI‖Seq，不含 IV**
//	校验顺序            **先验 ICV 再解密**（防 padding oracle）  GCM 自带
//
// ★最后一行的 AAD 差异是本文件最值得盯的一处：IKEv2 的 SK 载荷（RFC 5282）AAD 覆盖到
// IV 末字节，ESP（RFC 4106）**只覆盖 SPI‖Seq**。把 SK 那套照抄过来，白帝↔白帝依然全绿
// （两端犯同一个错），只有跟第三方对接时才炸——自证测试对这类错误完全无效。
// 因此 kat_test.go 用 crypto/cipher 独立按 RFC 4106 算一遍并逐字节比对，
// 那条测试才是「加密是真的、且口径是标准的」的唯一证据。
//
// # 明确不实现（是「本轮定义之外」，不是「还没做」）
//
//   - 裸 ESP（IP proto 50）、AH、IPComp；
//   - 传输模式（只做隧道模式）；
//   - ESN（扩展序号，64 位）——序号固定 32 位，用尽即拒发并要求 rekey，绝不回绕；
//   - TFC padding 与哑包（NextHeader=59）；
//   - 多 TS 对与 narrowing（一条 SA 只有一对 CIDR）；
//   - PMTUD——超长内层包**丢弃并计数**，不静默截断（静默截断的症状是
//     「能 ping 通、HTTP 卡住」，是最难查的一类）；
//   - 组播 / 多播 SA、SA 束（SA bundle）。
//
// # 计数口径
//
// RxBytes/TxBytes 计的是 **ESP 线上字节**（含头/IV/补齐/ICV），不是内层明文长度——
// 控制台上的「隧道流量」应当与网卡上真实跑的量对得上。丢弃的包不进 Counters，
// 只进 Drops：把丢包混进流量数字，等于让「通了」和「一直在丢」长得一样。
