/**
 * 首登强制改密（FR-DEPLOY-09）的端上纯逻辑：要求文案 + 提交前的本地校验。
 *
 * 背景：`BAIDI_SEED_MUST_CHANGE` 默认 1，`handleCreateUser` 对每个新建普通用户无条件置
 * `MustChangePw`，管理员每次重置口令同理。于是**每台按脚本装出来的机器上、每一个新用户**
 * 的首次登录，控制面回的都是 `{ok:true, mustChangePassword:true, token:<15min 受限令牌>}`——
 * 移动端此前只看 `r.ok && r.token` 就 `login()` 并跳主界面，之后每一个业务端点（接入配置、
 * 敲门令牌、应用列表）都被 `auth.Middleware` 的用途闸 403 掉，而界面上既没有改密入口、
 * 也没有一句话说明为什么。
 *
 * ★为什么做成端内改密而不是"请去浏览器门户改"：受限令牌本来就能调
 * `POST /api/v1/auth/password`（`auth.pwResetAllowed` 白名单里的两条之一），
 * 做得到就不该把人踢去另一个程序——尤其这台手机可能正是因为还没接入才连不上门户。
 *
 * 单独一个**零依赖**模块：它要被 node 里的用例直接 import（.vue 组件跑不起来，
 * api.ts 顶层就读 localStorage），而这段判定正是最该被真行为测试钉住的部分。
 */

/**
 * 当面写给用户看的口令要求。
 *
 * ★两个数字必须与控制面 `auth.minStrongLen`(10) / `auth.longPassphraseLen`(16) 一致，
 *   有跨轨守卫钉住（tests/pwchange.test.ts 直接读 control/internal/auth/strength.go）。
 *   端上写 8 位而后端判 10 位的话，用户会一次次提交"照着提示写的"口令、一次次被 400 顶回来；
 *   而首登改密是每套标准部署里每个新用户的**第一个动作**，卡在这里等于这台机器上
 *   一个终端用户都接入不了。
 *
 * ★但**判据只在后端**：客户端刻意不复刻强度算法（弱口令表 / 含账号名 / 连续字符）。
 *   复刻一份必然出现两种分歧——端上放行而后端拒收（用户看到一句自相矛盾的报错），
 *   或端上拦下而后端本可接受（用户被自己的客户端挡在门外，管理员那侧查不到任何记录）。
 *   这一行只负责"把要求说清楚"，不负责判定；真被拒时原样转述后端那句话。
 */
export const PW_RULE_HINT =
  '新口令要求：至少 10 位，且含大写 / 小写 / 数字 / 符号中的三类；'
  + '16 位以上的长口令不限字符种类。不得包含账号名、不得与原口令相同，也不得是常见弱口令。';

/**
 * 提交前的本地校验，返回第一条错误文案；全部通过回 `null`。
 *
 * 只做三件事，一件都不越界：
 *  - 空口令：后端会回「口令为空」，但白跑一个 RTT 且那句话不如当面提示；
 *  - 两次不一致：**后端根本判不了**（它只收到一个 new），不在这里判就没有任何地方判；
 *  - 与原口令相同：与后端 `body.New == body.Old` 逐字同一条规则，不存在分歧空间。
 *
 * 强度一律交给后端——理由见 PW_RULE_HINT 的第二段。
 */
export function checkNewPassword(pw: string, confirm: string, oldPw: string): string | null {
  if (!pw) return '请输入新口令';
  if (pw !== confirm) return '两次输入的新口令不一致';
  if (oldPw && pw === oldPw) return '新口令不得与原口令相同（换汤不换药会让「首登强制改密」形同虚设）';
  return null;
}
